import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import assert from 'node:assert/strict'
import sharp from 'sharp'

const root = fileURLToPath(new URL('../', import.meta.url))
const entries = [
  ['manoel', 'manoel-neto', 'manoel-neto-estudio-v2.png'],
  ['ronan', 'ronan-severo', 'ronan-severo-estudio-v2.png'],
  ['yuri', 'yuri-gabriel', 'yuri-gabriel-estudio-v2.png'],
  ['maksuel', 'maksuel-silva', 'macsuel-silva-estudio-v2.png'],
]
const destination = path.join(root, 'public/team/optimized')
await fs.mkdir(destination, { recursive: true })
const photos = {}
const report = []

for (const [id, name, sourceName] of entries) {
  const source = await fs.readFile(path.join(root, 'public/team', sourceName))
  const original = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  const encoded = await sharp(source)
    .keepIccProfile()
    .webp({ lossless: true, exact: true, effort: 6 })
    .toBuffer()
  const decoded = await sharp(encoded).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  assert.deepEqual(decoded.info, original.info, `${name}: dimensions/channels changed`)
  assert.ok(decoded.data.equals(original.data), `${name}: decoded pixels differ`)
  assert.ok(encoded.length < source.length, `${name}: lossless output is not smaller`)
  const hash = createHash('sha256').update(encoded).digest('hex')
  const filename = `${name}-${hash.slice(0, 12)}.webp`
  await fs.writeFile(path.join(destination, filename), encoded)
  photos[id] = {
    src: `/team/optimized/${filename}`,
    fallback: `/team/${sourceName}`,
    width: decoded.info.width,
    height: decoded.info.height,
  }
  report.push({
    id,
    source: `public/team/${sourceName}`,
    localPath: `public/team/optimized/${filename}`,
    objectKey: `team/${filename}`,
    width: decoded.info.width,
    height: decoded.info.height,
    sourceBytes: source.length,
    optimizedBytes: encoded.length,
    savedPercent: Number(((1 - encoded.length / source.length) * 100).toFixed(2)),
    pixelsIdentical: true,
    sha256: hash,
    decodedPixelsSha256: createHash('sha256').update(decoded.data).digest('hex'),
  })
}

await fs.mkdir(path.join(root, 'src/data'), { recursive: true })
await fs.writeFile(
  path.join(root, 'src/data/teamPhotos.ts'),
  `// Generated by npm run photos:optimize. Original portraits are preserved.\nexport const teamPhotos = ${JSON.stringify(photos, null, 2)} as const\n`,
)
await fs.writeFile(
  path.join(root, 'docs/TEAM-PHOTO-OPTIMIZATION.json'),
  JSON.stringify(
    {
      format: 'WebP lossless',
      resized: false,
      verified: 'Identical decoded RGBA bytes, including transparency',
      photos: report,
    },
    null,
    2,
  ) + '\n',
)
console.table(
  report.map(({ id, sourceBytes, optimizedBytes, savedPercent, pixelsIdentical }) => ({
    id,
    sourceBytes,
    optimizedBytes,
    savedPercent,
    pixelsIdentical,
  })),
)
